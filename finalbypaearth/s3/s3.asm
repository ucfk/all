; =========================================================
; ?????????????? MAX7219 (SPI Bit-Banging)
; =========================================================
INIT_MAX7219:
        MOV R2, #0BH          ; Scan Limit (??? 8 ???)
        MOV R3, #07H
        LCALL SEND_SPI
        
        MOV R2, #09H          ; Decode Mode (??????????)
        MOV R3, #00H
        LCALL SEND_SPI
        
        MOV R2, #0AH          ; Intensity (????????????????)
        MOV R3, #07H
        LCALL SEND_SPI
        
        MOV R2, #0CH          ; Shutdown Reg (?????????????)
        MOV R3, #01H
        LCALL SEND_SPI
        RET

SEND_SPI:
        CLR CS
        MOV A, R2
        LCALL SHIFT_OUT
        MOV A, R3
        LCALL SHIFT_OUT
        SETB CS
        RET

SHIFT_OUT:
        MOV R4, #08H
SO_LOOP:
        RLC A
        MOV DIN, C
        SETB CLK
        CLR CLK
        DJNZ R4, SO_LOOP
        RET


; =========================================================
; ????????????????? (Debounce)
